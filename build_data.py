"""Generate data/wada.js from data/colors.json.

colors.json is the open digitization of Sanzo Wada's "A Dictionary of Color
Combinations" (https://github.com/mattdesl/dictionary-of-colour-combinations).
Spot-checked against the scanned PDF in this folder (combos 7, 8, 183, 184, 290).

The output is a plain script (not JSON) so index.html works when opened
directly from disk, without a local server.
"""
import json
from collections import defaultdict
from pathlib import Path

here = Path(__file__).parent
colors = json.loads((here / "data" / "colors.json").read_text())

combos = defaultdict(list)
for i, c in enumerate(colors):
    for n in c["combinations"]:
        combos[n].append(i)

out = {
    "colors": [{"name": c["name"], "hex": c["hex"], "cmyk": c["cmyk"]} for c in colors],
    "combos": [{"id": n, "colors": combos[n]} for n in sorted(combos)],
}
(here / "data" / "wada.js").write_text(
    "// Generated by build_data.py — do not edit.\nwindow.WADA = " + json.dumps(out, separators=(",", ":")) + ";\n"
)
print(f"{len(out['colors'])} colors, {len(out['combos'])} combos")
